const fs = require('fs');

// 1. Read quran.ts to build a map: "surahId:ayahNumber" -> authentic Uthmani text
const quranContent = fs.readFileSync('./data/quran.ts', 'utf8');

// Parse ayahs from quran.ts
const ayahMap = new Map();
const ayahRegex = /surahId:\s*(\d+),\s*ayahNumber:\s*(\d+),\s*text:\s*'([^']+)'/g;
let m;
while ((m = ayahRegex.exec(quranContent)) !== null) {
  const sId = parseInt(m[1]);
  const aNum = parseInt(m[2]);
  const text = m[3];
  ayahMap.set(`${sId}:${aNum}`, text);
}
console.log('Indexed authentic ayahs from quran.ts:', ayahMap.size);

function getAyahs(list) {
  return list.map(([surahId, ayahNumber]) => {
    const text = ayahMap.get(`${surahId}:${ayahNumber}`);
    if (!text) {
      console.warn(`Missing ayah: ${surahId}:${ayahNumber}`);
    }
    return {
      surahId,
      ayahNumber,
      text: text || ''
    };
  }).filter(a => !!a.text);
}

