import glob
import re

tafsir_files = glob.glob('noor-app/data/tafsir/*.ts')

replacements = [
    # prefixes
    ('لِءَادَمَ', 'لِآدَمَ'),
    ('لِءَادَمُ', 'لِآدَمُ'),
    ('لِـءَادَمَ', 'لِآدَمَ'),
    ('بِٱلْءَاخِرَةِ', 'بِالْآخِرَةِ'),
    ('وَٱلْءَاخِرَةِ', 'وَالْآخِرَةِ'),
    ('فِى ٱلْءَاخِرَةِ', 'فِي الْآخِرَةِ'),
    ('ٱلْءَاخِرَةِ', 'الْآخِرَةِ'),
    ('ٱلْءَاخِرَةُ', 'الْآخِرَةُ'),
    ('ٱلْءَاخِرِ', 'الْآخِرِ'),
    ('وَبِالْءَاخِرَةِ', 'وَبِالْآخِرَةِ'),
    ('بِالْءَاخِرَةِ', 'بِالْآخِرَةِ'),
    ('الْءَاخِرَةِ', 'الْآخِرَةِ'),
    ('الْءَاخِرَةُ', 'الْآخِرَةُ'),
    ('الْءَاخِرِ', 'الْآخِرِ'),
    ('ءَادَمَ', 'آدَمَ'),
    ('ءَادَمُ', 'آدَمُ'),
    ('ءَامَنُوا', 'آمَنُوا'),
    ('ءَامَنَ', 'آمَنَ'),
    ('ءَامِنُوا', 'آمِنُوا'),
    ('ءَاتَيْنَا', 'آتَيْنَا'),
    ('ءَاتَاهُمُ', 'آتَاهُمُ'),
    ('ءَاتَىٰكُمْ', 'آتَاكُمْ'),
    ('ءَاتَىٰكُم', 'آتَاكُمْ'),
    ('ءَاتَاهُ', 'آتَاهُ'),
    ('ءَاتَيْنَاكُم', 'آتَيْنَاكُمْ'),
    ('ءَايَاتِ', 'آيَاتِ'),
    ('ءَايَاتُ', 'آيَاتُ'),
    ('ءَايَاتِنَا', 'آيَاتِنَا'),
    ('ءَايَةً', 'آيَةً'),
    ('ءَايَةٌ', 'آيَةٌ'),
    ('ءَاذَانِهِم', 'آذَانِهِمْ'),
    ('ءَالِهَتِنَا', 'آلِهَتِنَا'),
    ('ءَالِهَةً', 'آلِهَةً'),
    ('ءَالِ', 'آلِ'),
]

total_fixed = 0
for fpath in tafsir_files:
    with open(fpath, 'r', encoding='utf-8') as f:
        content = f.read()

    orig_content = content
    for old_w, new_w in replacements:
        content = content.replace(old_w, new_w)

    # Also any remaining ءَا preceded by alif-lam or standalone
    content = re.sub(r'ٱ?لْءَا', 'الْآ', content)
    content = re.sub(r'(^|\s)ءَا', r'\1آ', content)

    if content != orig_content:
        with open(fpath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Cleaned {fpath}")

print("Tafsir files cleaned!")
